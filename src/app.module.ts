// =====================================================================
// app.module.ts - THE ROOT MODULE  (master branch: no authentication yet)
// =====================================================================
// A NestJS app is a tree of MODULES. Each module is a "box" that groups a
// feature (its controllers, services, entities). AppModule is the root of
// the tree: Nest starts here and follows every `imports` to discover the
// whole application.

import { Module } from '@nestjs/common';
//these are the modules used to configure the application and connect to the database
// ConfigModule  -> loads the .env file and gives us ConfigService to read it.
// ConfigService -> the class we inject to read values like DB_HOST.
import { ConfigModule, ConfigService } from '@nestjs/config';
// TypeOrmModule -> the bridge between Nest and TypeORM (the ORM that talks to Postgres).
import { TypeOrmModule } from '@nestjs/typeorm';
// AppController / AppService are the "Hello World" pair generated by `nest new`.
// They are not used by the exercise (they only serve GET /), but harmless.
import { AppController } from './app.controller';
import { AppService } from './app.service';
import { SkillModule } from './skill/skill.module';
import { UserModule } from './user/user.module';
import { CvModule } from './cv/cv.module';

@Module({
  // `imports` = the other modules this module needs. The ORDER does not
  // matter to Nest; it resolves dependencies by itself.
  imports: [
    // The three feature modules (generated with `nest g resource`)...
    SkillModule,
    UserModule,
    CvModule,

    // Reads the .env file at startup and puts the values in process.env.
    // isGlobal: true  -> ConfigService can be injected in ANY module without
    // importing ConfigModule again each time.
    ConfigModule.forRoot({ isGlobal: true }),

    // Database connection.
    //  - `forRootAsync` ("async") is used because the settings come from
    //    ConfigService, which Nest must build FIRST. A plain `forRoot({...})`
    //    would read process.env too early, before .env is loaded.
    //  - `inject: [ConfigService]` -> "give my factory function a ConfigService".
    //  - `useFactory` -> the function that returns the connection options.
    TypeOrmModule.forRootAsync({
      inject: [ConfigService],
      useFactory: (config: ConfigService) => ({
        type: 'postgres',
        host: config.get<string>('DB_HOST'),
        // NB: values from .env are always STRINGS ("5432"). The <number> is
        // only a TypeScript hint, it does not convert. The pg driver accepts
        // the string, so it works anyway.
        port: config.get<number>('DB_PORT'),
        username: config.get<string>('DB_USERNAME'),
        password: config.get<string>('DB_PASSWORD'),
        database: config.get<string>('DB_NAME'),
        // autoLoadEntities: every entity registered with
        // TypeOrmModule.forFeature([...]) in any module is picked up
        // automatically. No central list of entities to maintain.
        autoLoadEntities: true,
        // synchronize: on every startup TypeORM compares our entity classes
        // with the database and creates/alters tables to match.
        // Very convenient in development. DANGEROUS in production (it can
        // drop columns/data): real projects use migrations instead.
        synchronize: true,
      }),
    }),
  ],

  // Controllers/providers of the root module itself (the Hello World pair).
  controllers: [AppController],
  providers: [AppService],
})
export class AppModule {}
